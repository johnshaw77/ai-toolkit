export const CHAR_DOTS = 12 // 5 個點 + 間隔 → 每個字 6 格點位，每格點位 2 個 braille 點
export const GLYPH_ROWS = 7

/** 字型沒有的字（中文、全形）換成 ? */
export const normalize = (text: string): string =>
  [...text.toUpperCase()].map(c => (FONT[c] !== undefined ? c : '?')).join('')

export const glyph = (c: string): readonly number[] => FONT[c] ?? FONT['?']!

/** 第 i 個字、第 fy 列、第 fx 行亮不亮 */
const lit = (text: string, i: number, fx: number, fy: number): boolean =>
  fx >= 0 && fx < 5 && (((glyph(text[i] ?? ' ')[fy] ?? 0) >> (4 - fx)) & 1) === 1

export const textDots = (text: string): number => [...text].length * CHAR_DOTS

const GAP_DOTS = 24 // 跑完一輪後空兩個字再重來
const PAUSE_MS = 800 // 一開始先停一下讓人看清楚開頭
const DOTS_PER_MS = 0.02

/** 跑馬燈捲了幾個點；放得下就不捲 */
export function scrollOf(text: string, panelDots: number, ms: number): number {
  const len = textDots(text)
  if (len <= panelDots) return 0
  const moved = Math.max(0, ms - PAUSE_MS) * DOTS_PER_MS
  return Math.floor(moved) % (len + GAP_DOTS)
}

/** 面板上 (dx, dy) 這個 braille 點亮不亮（dy 從面板頂端算） */
export function dotAt(text: string, dx: number, dy: number, scroll: number, yOffset: number): boolean {
  const y = dy - yOffset
  if (y < 0 || y % 2 !== 0 || y / 2 >= GLYPH_ROWS) return false
  const loop = textDots(text) + GAP_DOTS
  const len = textDots(text)
  let x = dx + scroll
  if (len > 0 && scroll > 0) x %= loop
  if (x % 2 !== 0 || x < 0 || x >= len) return false
  const i = Math.floor(x / CHAR_DOTS)
  return lit(text, i, (x % CHAR_DOTS) / 2, y / 2)
}

// braille 一格：左行由上而下 0x01 0x02 0x04 0x40，右行 0x08 0x10 0x20 0x80
const BITS = [
  [0x01, 0x08],
  [0x02, 0x10],
  [0x04, 0x20],
  [0x40, 0x80],
] as const

/** 這個點位屬於第幾個字（上色用）；字之間的空白不算 */
export function charAt(text: string, dx: number, scroll: number): number {
  const len = textDots(text)
  let x = dx + scroll
  if (len > 0 && scroll > 0) x %= len + GAP_DOTS
  return Math.floor(x / CHAR_DOTS)
}

/** 一格 braille：code point 與亮點屬於第幾個字；全暗回傳 undefined（畫成空白） */
export function brailleAt(text: string, col: number, row: number, scroll: number, yOffset: number): { code: number; char: number } | undefined {
  let bits = 0
  let char = 0
  for (let r = 0; r < 4; r++) {
    for (let c = 0; c < 2; c++) {
      if (dotAt(text, col * 2 + c, row * 4 + r, scroll, yOffset)) {
        bits |= BITS[r]![c]!
        char = charAt(text, col * 2 + c, scroll)
      }
    }
  }
  return bits === 0 ? undefined : { code: 0x2800 + bits, char }
}
